/**
 * Stamps docs/sw.js for a release (spec §10): first regenerates docs/js/about-data.js (code
 * statistics shown on the about page), then rewrites the generated block with the list of
 * every shipped file (PRECACHE) and a content hash of those files (VERSION), so each release
 * gets one complete, versioned cache. Run `npm run stamp` after changing anything in docs/;
 * `npm test` fails while the stamp is stale. Not part of the app; Node built-ins only.
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DOCS_DIR = fileURLToPath(new URL('../docs/', import.meta.url));
export const SW_PATH = fileURLToPath(new URL('../docs/sw.js', import.meta.url));
export const TESTS_DIR = fileURLToPath(new URL('../tests/', import.meta.url));
export const APPS_SCRIPT_PATH = fileURLToPath(new URL('../apps-script/Code.js', import.meta.url));
/** Generated by this script; shipped like any other file. Relative to docs/. */
export const ABOUT_DATA = 'js/about-data.js';

/** Published but not part of the app: the worker itself, the Pages domain file. */
const EXCLUDED = new Set(['sw.js', 'CNAME']);
const BLOCK = /(\/\/ BEGIN GENERATED[^\n]*\n)[\s\S]*?(\/\/ END GENERATED)/;

/**
 * Excludes the files above, dotfiles (.DS_Store, …) and Markdown (vendor licences).
 * @param {string} path relative to docs/, '/'-separated
 * @returns {boolean}
 */
export function isShippable(path) {
  const name = path.split('/').pop();
  return !EXCLUDED.has(path) && !path.split('/').some((part) => part.startsWith('.')) && !name.endsWith('.md');
}

/**
 * Every shipped file under docs/, relative and '/'-separated, sorted by code point.
 * @param {string} [dir]
 * @returns {string[]}
 */
export function shippableFiles(dir = DOCS_DIR) {
  return filesBelow(dir).filter(isShippable);
}

/**
 * Every file below dir, relative and '/'-separated, sorted by code point.
 * @param {string} dir
 * @returns {string[]}
 */
function filesBelow(dir) {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => `${entry.parentPath ?? entry.path}/${entry.name}`.slice(dir.length).replace(/^\/+/, '').split('\\').join('/'))
    .sort();
}

/**
 * Newline-separated lines; a final newline does not start another line.
 * @param {string} text
 * @returns {number}
 */
export function countLines(text) {
  if (text === '') return 0;
  return text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
}

/**
 * Code statistics for the about page. Files: every shipped file, about-data.js included even
 * before it exists. Lines: shipped .js/.css/.html, except the vendored Chart.js and
 * about-data.js itself. Test cases: lines starting with `test(` in every *.test.js under tests/.
 * @param {{ docsDir?: string, testsDir?: string, appsScriptPath?: string }} [paths]
 * @returns {{ files: number, lines: { js: number, css: number, html: number }, appsScriptLines: number, testFiles: number, testCases: number }}
 */
export function codeStats({ docsDir = DOCS_DIR, testsDir = TESTS_DIR, appsScriptPath = APPS_SCRIPT_PATH } = {}) {
  const shipped = new Set(shippableFiles(docsDir));
  shipped.add(ABOUT_DATA);
  const lines = { js: 0, css: 0, html: 0 };
  for (const path of shipped) {
    const ext = path.split('.').pop();
    if (!Object.hasOwn(lines, ext) || path === ABOUT_DATA || path.startsWith('vendor/')) continue;
    lines[ext] += countLines(readFileSync(`${docsDir}/${path}`, 'utf8'));
  }
  const testFiles = filesBelow(testsDir).filter((path) => path.endsWith('.test.js'));
  const testCases = testFiles
    .map((path) => readFileSync(`${testsDir}/${path}`, 'utf8').match(/^\s*test\(/gm)?.length ?? 0)
    .reduce((sum, n) => sum + n, 0);
  return {
    files: shipped.size,
    lines,
    appsScriptLines: countLines(readFileSync(appsScriptPath, 'utf8')),
    testFiles: testFiles.length,
    testCases,
  };
}

/**
 * Source of docs/js/about-data.js.
 * @param {ReturnType<typeof codeStats>} stats
 * @returns {string}
 */
export function renderAboutData({ files, lines, appsScriptLines, testFiles, testCases }) {
  return [
    '/** Code statistics for the about page. Generated by `npm run stamp` (scripts/stamp-sw.mjs); do not edit. */',
    'export const CODE_STATS = {',
    `  files: ${files},`,
    `  lines: { js: ${lines.js}, css: ${lines.css}, html: ${lines.html} },`,
    `  appsScriptLines: ${appsScriptLines},`,
    `  testFiles: ${testFiles},`,
    `  testCases: ${testCases},`,
    '};',
    '',
  ].join('\n');
}

/**
 * First 12 hex chars of SHA-256 over each path and its contents, in the given order.
 * @param {string[]} files relative to dir
 * @param {string} [dir]
 * @returns {string}
 */
export function computeVersion(files, dir = DOCS_DIR) {
  const hash = createHash('sha256');
  for (const path of files) {
    hash.update(`${path}\0`);
    hash.update(readFileSync(`${dir}/${path}`));
    hash.update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

/**
 * The generated block's contents.
 * @param {string} version
 * @param {string[]} files
 * @returns {string}
 */
export function renderBlock(version, files) {
  return `const VERSION = '${version}';\nconst PRECACHE = [\n${files.map((path) => `  '${path}',\n`).join('')}];\n`;
}

/**
 * Rewrites the generated block of sw.js source.
 * @param {string} source
 * @param {string} version
 * @param {string[]} files
 * @returns {string}
 */
export function stamp(source, version, files) {
  if (!BLOCK.test(source)) throw new Error('sw.js has no "// BEGIN GENERATED … // END GENERATED" block');
  return source.replace(BLOCK, (_, begin, end) => `${begin}${renderBlock(version, files)}${end}`);
}

// Run as a script (also through a symlinked path), not when imported by the tests.
if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  // about-data.js first: it is shipped, so it belongs in PRECACHE and in the VERSION hash.
  const aboutPath = `${DOCS_DIR}/${ABOUT_DATA}`;
  const aboutData = renderAboutData(codeStats());
  if (!existsSync(aboutPath) || readFileSync(aboutPath, 'utf8') !== aboutData) writeFileSync(aboutPath, aboutData);
  const files = shippableFiles();
  const version = computeVersion(files);
  const source = readFileSync(SW_PATH, 'utf8');
  const stamped = stamp(source, version, files);
  if (stamped !== source) writeFileSync(SW_PATH, stamped);
  console.log(`sw.js: VERSION ${version}, ${files.length} files${stamped === source ? ' (unchanged)' : ''}`);
}
