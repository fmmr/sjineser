const CACHE = `sjineser-${VERSION}`;
const CACHE_PREFIX = 'sjineser-';

const scopeUrl = new URL(self.registration.scope);
const indexUrl = new URL('index.html', scopeUrl).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((path) => new Request(new URL(path, scopeUrl), { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE).map((key) => caches.delete(key)),
      ))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== scopeUrl.origin) return;
  const isApp = request.mode === 'navigate'
    && (url.pathname === scopeUrl.pathname || url.origin + url.pathname === indexUrl);
  event.respondWith(cacheFirst(request, isApp ? indexUrl : request));
});

/**
 * From the current version's cache, else from the network (without caching the answer).
 * @param {Request} request what the page asked for
 * @param {Request | string} key the cache entry that answers it
 * @returns {Promise<Response>}
 */
async function cacheFirst(request, key) {
  const cache = await caches.open(CACHE);
  return (await cache.match(key)) ?? fetch(request);
}
